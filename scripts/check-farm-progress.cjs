const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const ts = require("typescript");
const filename = path.resolve(__dirname, "../src/utils/farmProgress.ts");
const compiled = ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const domain = new Module(filename, module);
domain._compile(compiled.outputText, filename);
const p = domain.exports;
const today = new Date(2026, 10, 3, 12).getTime();
const tomorrow = new Date(2026, 10, 4, 0, 1).getTime();
let journal = p.emptyJournal(today);
assert.equal(p.claimGoal(journal, "harvest", today).reward, 0, "unfinished goals cannot pay");
journal = p.recordActivity(journal, "harvest", 8, today);
assert.equal(journal.counts.harvest, 3, "progress is capped at target");
const claim = p.claimGoal(journal, "harvest", today);
assert.equal(claim.reward, 30);
assert.equal(p.claimGoal(claim.journal, "harvest", today).reward, 0, "repeated claim cannot pay twice");
assert.equal(p.claimGoal(journal, "harvest", tomorrow).reward, 0, "yesterday's progress cannot claim today's reward");
assert.deepEqual(p.restoreJournal(claim.journal, tomorrow), p.emptyJournal(tomorrow));
assert.deepEqual(p.restoreJournal(undefined, today), p.emptyJournal(today), "old saves get a clean journal");
assert.deepEqual(p.restoreJournal({ date: p.realDate(today), counts: { plant: NaN, water: -2, harvest: Infinity }, claimed: ["plant", "harvest"] }, today), p.emptyJournal(today), "invalid progress cannot unlock rewards");
assert.equal(p.recordActivity(journal, "plant", 1, tomorrow).counts.plant, 1);
assert.equal(p.farmLevel(0), 1);
assert.equal(p.farmLevel(8), 2);
assert.equal(p.farmLevel(24), 4);
assert.equal(p.waterCapacity(0), 3);
assert.equal(p.waterCapacity(999), 12);
assert.equal(p.waterCapacity(-5), 3);
assert.equal(p.upgradeCost(0), 90);
assert.equal(p.compostReward(3), 0);
assert.equal(p.compostReward(4), 1);
assert.equal(p.compostReward(999), 5);
assert.equal(p.qualityPrice(20, true), 23);
assert.equal(p.qualityPrice(48, false), 48);
assert.equal(p.fertilizedGrowth(95, 100), 100, "fertilizer cannot overgrow a crop");
assert.equal(p.fertilizedGrowth(0, 100), 25);
assert.equal(p.remainingGrowthTime(100, 100), 100);
assert.equal(p.remainingGrowthTime(100, 30), 230, "ETA includes slower growth after soil dries");
console.log("Farm progression checks passed: claims, daily reset, old-save defaults, bad data, levels, caps, fertilizer and growth ETA.");
