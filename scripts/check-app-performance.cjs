const assert = require('node:assert/strict');
const load = require('./load-project-ts.cjs')();
const { createCoalescedWriter } = load('src/utils/coalescedWriter.ts');
const { createRequestCoordinator } = load('src/utils/requestCoordinator.ts');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const deferred = () => { let resolve; const promise = new Promise(done => { resolve = done; }); return { promise, resolve }; };
async function main() {
  const { renderQuality } = load('src/utils/renderQuality.ts');
  assert.equal(renderQuality('smooth').rain, false);
  assert.equal(renderQuality('smooth').blur, false);
  assert.equal(renderQuality('smooth').idleAnimation, false);
  assert(renderQuality('beautiful').particles > renderQuality('standard').particles);
  assert.deepEqual(renderQuality('unknown-old-setting'), renderQuality('standard'));
  const { plotStage, isWet } = load('src/utils/farmPlot.ts');
  const { CROP_META } = load('src/utils/farmEconomy.ts');
  const crop = { crop: 'radish', growMs: CROP_META.radish.growMs * 0.45, lastSync: 1000, wetUntil: 2000 };
  assert.equal(plotStage(crop, 1000), 1);
  assert.equal(plotStage({ ...crop, growMs: CROP_META.radish.growMs }, 1000), 2);
  assert.equal(isWet(crop, 1999), true); assert.equal(isWet(crop, 2000), false);
  const summary = require('./summarize-android-performance.cjs');
  assert.equal(summary('Total frames rendered: 200\nJanky frames: 4 (2.00%)', '', '').jankyPercent, 2);
  assert.equal(summary('', '', '').frames, null, 'missing frame measurements must never be reported as zero jank');
  const saves = [], first = deferred();
  const writer = createCoalescedWriter(async value => { saves.push(value); if (value === 10) await first.promise; }, 10);
  for (let i = 0; i <= 10; i++) writer.schedule(i);
  await wait(25); assert.deepEqual(saves, [10], 'a rapid burst writes only its latest value');
  for (let i = 11; i <= 20; i++) writer.schedule(i);
  const flushed = writer.flush(); first.resolve(); await flushed;
  assert.deepEqual(saves, [10, 20], 'an active write has at most one newest pending successor');
  writer.dispose();
  let failing = true;
  const retry = createCoalescedWriter(async value => { if (failing) throw new Error('disk'); saves.push(value); }, 10000);
  retry.schedule(21); await assert.rejects(retry.flush(), /disk/);
  failing = false; await retry.flush(); assert.equal(saves.at(-1), 21, 'failed writes remain available for a flush retry'); retry.dispose();

  const coordinator = createRequestCoordinator();
  const bg = deferred(), user = deferred(), order = [];
  const a = coordinator.run(async () => { order.push('bg'); await bg.promise; }, { priority: 'background' });
  const b = coordinator.run(async () => { order.push('user'); await user.promise; });
  const c = coordinator.run(async () => { order.push('bg2'); }, { priority: 'background' });
  const d = coordinator.run(async () => { order.push('user2'); });
  await Promise.resolve(); assert.deepEqual(order, ['bg', 'user']);
  assert.equal(coordinator.getSnapshot().active, 2);
  bg.resolve(); await a; await wait(0);
  assert.equal(order[2], 'user2', 'foreground work overtakes queued background work');
  user.resolve(); await Promise.all([b, c, d]); await wait(0);
  assert.equal(coordinator.getSnapshot().active, 0);
  const block = deferred();
  const running = coordinator.run(async () => block.promise, { priority: 'background' });
  const cancelled = new AbortController();
  const queued = coordinator.run(async () => { throw new Error('must never start'); }, { signal: cancelled.signal, priority: 'background' });
  cancelled.abort(); await assert.rejects(queued, /取消/); block.resolve(); await running; await wait(0);
  const controller = new AbortController();
  const active = coordinator.run(signal => new Promise((_, reject) => signal.addEventListener('abort', () => reject(new Error('aborted')), { once: true })), { signal: controller.signal });
  await Promise.resolve(); controller.abort(); await assert.rejects(active, /aborted/); await wait(0);
  const all = coordinator.run(signal => new Promise((_, reject) => signal.addEventListener('abort', () => reject(new Error('all cancelled')), { once: true })));
  await Promise.resolve(); coordinator.setPaused(true); await assert.rejects(all, /cancelled/);
  await assert.rejects(coordinator.run(async () => 1), /取消/); coordinator.setPaused(false);
  const records = coordinator.getSnapshot().recent;
  assert(records.length <= 20 && records.every(row => !('content' in row)), 'diagnostics stay bounded and exclude message content');
  console.log('PASS: coalesced saves, in-flight write ordering, failed-write retry, bounded AI concurrency, foreground priority, queued/running cancellation and restore suspension');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
